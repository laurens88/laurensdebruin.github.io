// Draws the small continent maps on the travel page from worldmap.svg, antarctica.svg and travel.json.
// Runs before `npm start` and `npm run build`, so the pictures always match the visited countries.
// Output: src/generated/continentMaps/<continent>-<light|dark>.svg plus an index.js that imports them.
const fs = require("fs");
const path = require("path");

const src = path.join(__dirname, "..", "src");
const out = path.join(src, "generated", "continentMaps");
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(src, file), "utf8"));

const travel = readJson("data/travel.json");
const regions = readJson("data/mapRegions.json");
const continentCodes = readJson("data/continentCodes.json");

const continentOf = {};
for (const [continent, codes] of Object.entries(continentCodes)) {
  for (const code of codes.split(" ")) continentOf[code] = continent;
}
const visited = new Set(travel.countries.flatMap((c) => c.map || [c.code]));

// Same colours as styles/worldmap.module.css.
const themes = {
  light: { land: "#dbdbdb", other: "#f0f0f0", visited: "#1101fa", otherVisited: "#bdb9fd", border: "#ffffff" },
  dark: { land: "#101560", other: "#05082e", visited: "#1101fa", otherVisited: "#2c2a8a", border: "#000323" },
};

function readPaths(file) {
  const svg = fs.readFileSync(path.join(src, file), "utf8");
  return [...svg.matchAll(/<path\b([^>]*?)\/>/g)].map(([, attrs]) => {
    const attr = (name) => (attrs.match(new RegExp(`\\b${name}="([^"]*)"`)) || [])[1];
    const d = attr("d");
    return { code: attr("data-country") || null, d, box: bounds(d) };
  });
}

// Bounding box of a path made of m/l/z commands (absolute or relative).
function bounds(d) {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g);
  let x = 0, y = 0, startX = 0, startY = 0, cmd = "M", first = true;
  const box = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
  for (let i = 0; i < tokens.length; ) {
    if (/[a-zA-Z]/.test(tokens[i])) {
      cmd = tokens[i++];
      if (cmd === "z" || cmd === "Z") { x = startX; y = startY; }
      continue;
    }
    const a = parseFloat(tokens[i++]), b = parseFloat(tokens[i++]);
    const absolute = cmd === cmd.toUpperCase() || first;
    x = absolute ? a : x + a;
    y = absolute ? b : y + b;
    if (cmd === "m" || cmd === "M") { startX = x; startY = y; cmd = cmd === "m" ? "l" : "L"; }
    first = false;
    box.minX = Math.min(box.minX, x); box.maxX = Math.max(box.maxX, x);
    box.minY = Math.min(box.minY, y); box.maxY = Math.max(box.maxY, y);
  }
  return box;
}

function draw(continent, shapes, theme) {
  const [x, y, w, h] = regions[continent].split(" ").map(Number);
  const t = themes[theme];
  const body = shapes
    .filter(({ box }) => box.maxX >= x && box.minX <= x + w && box.maxY >= y && box.minY <= y + h)
    .map(({ code, d }) => {
      const isVisited = code && visited.has(code);
      const inside = continentOf[code] === continent;
      const fill = inside ? (isVisited ? t.visited : t.land) : (isVisited ? t.otherVisited : t.other);
      return `<path fill="${fill}" stroke="${t.border}" stroke-width="0.25" stroke-linejoin="round" d="${d}"/>`;
    })
    .join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${regions[continent]}">\n${body}\n</svg>\n`;
}

const world = readPaths("assets/images/worldmap.svg");
const antarctica = readPaths("assets/images/antarctica.svg");
const slug = (name) => name.toLowerCase().replace(/[^a-z]+/g, "-");

fs.mkdirSync(out, { recursive: true });
const imports = [];
const entries = [];
for (const continent of Object.keys(regions).filter((name) => name !== "World")) {
  const shapes = continent === "Antarctica" ? antarctica : world;
  const names = {};
  for (const theme of Object.keys(themes)) {
    const file = `${slug(continent)}-${theme}.svg`;
    fs.writeFileSync(path.join(out, file), draw(continent, shapes, theme));
    names[theme] = `${slug(continent).replace(/-./g, (m) => m[1].toUpperCase())}${theme[0].toUpperCase()}${theme.slice(1)}`;
    imports.push(`import ${names[theme]} from "./${file}";`);
  }
  entries.push(`  ${JSON.stringify(continent)}: { light: ${names.light}, dark: ${names.dark} },`);
}
fs.writeFileSync(path.join(out, "index.js"),
  `// Generated by scripts/continentMaps.js — do not edit.\n${imports.join("\n")}\n\nconst continentMaps = {\n${entries.join("\n")}\n};\n\nexport default continentMaps;\n`);
console.log(`continent maps written for ${entries.length} continents`);
